"""Consolidated benchmark report for the NLP FA Failure Classifier.

Reads every `v*_all_results.csv` (and similarly named) file under `results/`,
normalizes the columns, ranks configurations by Macro-F1, and emits:

- reports/benchmark_summary.json
- reports/benchmark_report.md

No retraining. This is a reporting-only script: every number comes directly
from saved experiment CSVs.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS = REPO_ROOT / "results"
REPORTS = REPO_ROOT / "reports"

CANDIDATES = [
    ("v6", RESULTS / "v6_all_results.csv"),
    ("v7a_group_split", RESULTS / "v7a_group_split_results.csv"),
    ("v7b_crossval", RESULTS / "v7b_crossval_results.csv"),
    ("v7c_ensemble", RESULTS / "v7c_ensemble_results.csv"),
    ("v5a", RESULTS / "v5a_all_results.csv"),
    ("v4_improved", RESULTS / "v4_improved_all_results.csv"),
]


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _num(x: str | None) -> float | None:
    if x is None or x == "":
        return None
    try:
        return float(x)
    except ValueError:
        return None


def main() -> int:
    all_runs: list[dict] = []
    per_suite_summary: dict[str, dict] = {}

    for suite, path in CANDIDATES:
        if not path.exists():
            continue
        rows = _read_csv(path)
        suite_runs = []
        for r in rows:
            macro_f1 = _num(r.get("Macro-F1"))
            if macro_f1 is None:
                continue
            entry = {
                "suite": suite,
                "model": r.get("Model") or r.get("Experiment") or "unknown",
                "macro_f1": macro_f1,
                "accuracy": _num(r.get("Accuracy")),
                "eos_precision": _num(r.get("EOS-Prec")),
                "eos_recall": _num(r.get("EOS-Rec")),
                "eos_f1": _num(r.get("EOS-F1")),
            }
            suite_runs.append(entry)
            all_runs.append(entry)
        if suite_runs:
            best = max(suite_runs, key=lambda e: e["macro_f1"])
            per_suite_summary[suite] = {
                "n_runs": len(suite_runs),
                "best": best,
            }

    overall_best = max(all_runs, key=lambda e: e["macro_f1"]) if all_runs else None

    summary = {
        "total_runs": len(all_runs),
        "suites_parsed": sorted(per_suite_summary.keys()),
        "per_suite": per_suite_summary,
        "overall_best": overall_best,
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "benchmark_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )

    lines = [
        "# NLP FA Failure Classifier \u2014 Benchmark Report",
        "",
        "Generated by `scripts/generate_benchmark_report.py` from saved "
        "experiment CSVs in `results/`. No retraining.",
        "",
        f"- **Total configurations parsed:** {len(all_runs)}",
        f"- **Experiment suites:** {', '.join(summary['suites_parsed'])}",
        "",
        "## Per-suite best configuration",
        "",
        "| Suite | # runs | Best model | Macro-F1 | Accuracy | EOS-F1 |",
        "|-------|--------|------------|----------|----------|--------|",
    ]
    for suite in summary["suites_parsed"]:
        info = per_suite_summary[suite]
        best = info["best"]
        lines.append(
            f"| {suite} | {info['n_runs']} | `{best['model']}` | "
            f"{best['macro_f1']:.4f} | "
            f"{best['accuracy']:.4f} | "
            f"{(best['eos_f1'] or 0):.4f} |"
        )

    if overall_best:
        lines += [
            "",
            "## Overall champion",
            "",
            f"- **Model:** `{overall_best['model']}` (suite: {overall_best['suite']})",
            f"- **Macro-F1:** {overall_best['macro_f1']:.4f}",
            f"- **Accuracy:** {overall_best['accuracy']:.4f}",
            f"- **EOS precision / recall / F1:** "
            f"{overall_best['eos_precision']:.4f} / "
            f"{overall_best['eos_recall']:.4f} / "
            f"{overall_best['eos_f1']:.4f}",
        ]

    (REPORTS / "benchmark_report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Parsed {len(all_runs)} runs from {len(summary['suites_parsed'])} suites")
    print(f"Wrote {REPORTS / 'benchmark_summary.json'}")
    print(f"Wrote {REPORTS / 'benchmark_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
